// Формулы моделей для превью в списке уравнений.
//
// Здесь ничего не считается: это то же уравнение, что решает `models/*.js`, но
// свёрстанное для чтения — с подсветкой членов и подписью к каждому. Разметка
// написана руками, а не собрана из разбора формулы: моделей семь, парсера
// уравнений в проекте нет, и заводить его ради семи строк дороже, чем весь
// выигрыш (в соседнем difur парсер есть, там формула строится по AST).
//
// ЛОВУШКА: расхождение формулы с солвером молчаливое — картинка останется
// правдоподобной. Меняешь L(k) или нелинейность в модели — правь и здесь.
//
// Классы подсветки (цвета живут в index.html, рядом с остальным UI):
//   k-nl    нелинейность — то, что фокусирует или опрокидывает
//   k-disp  дисперсия / дифракция — то, что расплывает
//   k-tr    поперечный член — то, из-за чего задача двумерная
//   k-fix   член, который меняет ответ: спасает от коллапса или ломает солитон

const U = '<i>u</i>';
const P = '<i>ψ</i>';
const LAP = '∇<sup>2</sup>';

// `extra` — для терма с дробью: там подсветка обязана стать flex-строкой,
// иначе знаменатель вываливается из подложки, а множитель уезжает наверх.
const tm = (cls, html, extra = '') => `<span class="tm k-${cls}${extra}">${html}</span>`;

